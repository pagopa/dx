/**
 * Recover the bootstrap module's GitHub resources using declarative imports.
 */
import { execa } from "execa";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { z } from "zod/v4";

import type { GitHubRepo } from "../../domain/github-repo.js";

import { parseTerraformJson } from "../../domain/repository-state.js";
import { terraformLiteral } from "./literal.js";
import { readOptionalFile } from "./repository-backend.js";

export type TerraformRunner = (args: string[]) => Promise<{ stdout: string }>;
export const repositoryRecoveryImportsName = "repository-state-imports.tf";
export const repositoryRecoveryImportsHeader =
  "# Generated by DX CLI repository state recovery.\n";

const resourceSchema = z.object({
  address: z
    .string()
    .regex(
      /^module\.github_repository\.(?:data\.)?[a-z_][a-z0-9_]*\.[a-z_][a-z0-9_]*(?:\[(?:"(?:[^"\\]|\\.)*"|\d+)\])?$/,
    ),
  change: z.object({
    actions: z.array(z.string()),
    after: z.record(z.string(), z.unknown()).nullable(),
  }),
  mode: z.enum(["managed", "data"]),
  type: z.string(),
});

const planSchema = z.object({
  resource_changes: z.array(resourceSchema),
});

const policiesSchema = z.array(
  z.object({
    branch_policies: z.array(
      z.object({
        id: z.number().int(),
        name: z.string(),
        type: z.enum(["branch", "tag"]).default("branch"),
      }),
    ),
  }),
);

const autolinksSchema = z.array(
  z.array(
    z.object({
      id: z.number().int(),
      key_prefix: z.string(),
    }),
  ),
);

export type GitHubJsonReader = (endpoint: string) => Promise<unknown>;
export type RepositoryImportResource = z.infer<typeof resourceSchema>;

export const readGitHubJson: GitHubJsonReader = async (endpoint) => {
  const result = await execa("gh", ["api", "--paginate", "--slurp", endpoint]);
  return JSON.parse(result.stdout);
};

const stringAttribute = (
  resource: RepositoryImportResource,
  name: string,
): string => {
  const value = z.string().min(1).safeParse(resource.change.after?.[name]);
  if (!value.success) {
    throw new Error(`Cannot determine ${name} for ${resource.address}.`);
  }
  return value.data;
};

export const repositoryImportId = async (
  resource: RepositoryImportResource,
  github: GitHubRepo,
  readJson: GitHubJsonReader,
): Promise<string | undefined> => {
  const repository = github.repo;
  switch (resource.type) {
    case "github_actions_repository_permissions":
    case "github_branch_default":
    case "github_repository":
    case "github_repository_vulnerability_alerts":
      return repository;
    case "github_branch":
      return `${repository}:${stringAttribute(resource, "branch")}`;
    case "github_branch_protection":
      return `${repository}:${stringAttribute(resource, "pattern")}`;
    case "github_repository_autolink_reference": {
      const response = autolinksSchema.safeParse(
        await readJson(
          `repos/${github.owner}/${repository}/autolinks?per_page=100`,
        ),
      );
      if (!response.success) {
        throw new Error("GitHub returned invalid autolink data.");
      }
      const matches = response.data
        .flat()
        .filter(
          (link) => link.key_prefix === stringAttribute(resource, "key_prefix"),
        );
      if (matches.length !== 1) {
        throw new Error(
          `Cannot uniquely identify autolink ${resource.address}.`,
        );
      }
      return `${repository}:${matches[0].id}`;
    }
    case "github_repository_environment":
      return `${repository}:${stringAttribute(resource, "environment").replaceAll(":", "??")}`;
    case "github_repository_environment_deployment_policy": {
      const environment = stringAttribute(resource, "environment");
      const branch = resource.change.after?.branch_pattern;
      const type =
        typeof branch === "string" && branch.length > 0 ? "branch" : "tag";
      const name = stringAttribute(resource, `${type}_pattern`);
      const response = policiesSchema.safeParse(
        await readJson(
          `repos/${github.owner}/${repository}/environments/${encodeURIComponent(environment)}/deployment-branch-policies?per_page=100`,
        ),
      );
      if (!response.success) {
        throw new Error("GitHub returned invalid deployment policy data.");
      }
      const matches = response.data
        .flatMap((page) => page.branch_policies)
        .filter((policy) => policy.name === name && policy.type === type);
      if (matches.length !== 1) {
        throw new Error(
          `Cannot uniquely identify deployment policy ${environment}/${name}.`,
        );
      }
      return `${repository}:${environment.replaceAll(":", "??")}:${matches[0].id}`;
    }
    case "null_resource":
      if (
        resource.address ===
        "module.github_repository.null_resource.workflow_permissions"
      ) {
        // null_resource cannot be imported. Its existing, idempotent provisioner
        // reasserts the declared workflow permissions when recovery is applied.
        return undefined;
      }
  }
  throw new Error(
    `Automatic repository recovery does not support ${resource.address}.`,
  );
};

const readRecoveryPlan = async (run: TerraformRunner, planFile: string) => {
  await run(["plan", "-input=false", `-out=${planFile}`]);
  const { stdout } = await run(["show", "-json", planFile]);
  const result = planSchema.safeParse(
    parseTerraformJson(stdout, "Terraform recovery plan"),
  );
  if (!result.success) {
    throw new Error(
      "Terraform returned an unsupported repository recovery plan.",
    );
  }
  if (
    result.data.resource_changes.some((resource) =>
      resource.change.actions.includes("delete"),
    )
  ) {
    throw new Error(
      "Repository state recovery would destroy or replace resources; refusing to apply.",
    );
  }
  return result.data.resource_changes;
};

export const recoverRepositoryState = async (
  repositoryPath: string,
  github: GitHubRepo,
  run: TerraformRunner,
  readJson: GitHubJsonReader = readGitHubJson,
): Promise<void> => {
  const directory = await fs.mkdtemp(
    path.join(os.tmpdir(), "dx-repository-recovery-"),
  );
  const planFile = path.join(directory, "recovery.tfplan");
  const importsFile = path.join(repositoryPath, repositoryRecoveryImportsName);
  try {
    const existingImports = await readOptionalFile(importsFile);
    if (
      existingImports !== undefined &&
      !existingImports.startsWith(repositoryRecoveryImportsHeader)
    ) {
      throw new Error(
        "The repository recovery imports file already exists with unexpected contents.",
      );
    }
    const resources = await readRecoveryPlan(run, planFile);
    if (existingImports === undefined) {
      const blocks: string[] = [];
      for (const resource of resources.filter(
        (resource) =>
          resource.mode === "managed" &&
          resource.change.actions.includes("create"),
      )) {
        const id = await repositoryImportId(resource, github, readJson);
        if (id !== undefined) {
          blocks.push(
            `import {\n  to = ${resource.address}\n  id = ${terraformLiteral(id)}\n}\n`,
          );
        }
      }
      if (blocks.length === 0) {
        throw new Error(
          "No GitHub resources were found to import for repository recovery.",
        );
      }
      await fs.writeFile(
        importsFile,
        repositoryRecoveryImportsHeader + blocks.join("\n"),
        { flag: "wx" },
      );
      await readRecoveryPlan(run, planFile);
    }
    await run(["apply", "-input=false", planFile]);
  } finally {
    await fs.rm(directory, { recursive: true });
  }
};
